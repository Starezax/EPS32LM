# Ймовірності
P_ADDR_START = 0.40
P_ADDR_END = 0.25
P_FOLLOW = 0.45


def weighted(rng, items):
    vals, ws = zip(*items)
    return rng.choices(vals, weights=ws, k=1)[0]


def lower_first(s):
    first = re.split(r"[\s,.!?:]", s, maxsplit=1)[0]
    if first in PROPER:
        return s
    return s[:1].lower() + s[1:]


def upper_first(s):
    return s[:1].upper() + s[1:]


def load_memories():
    mem = {"V": [], "D": [], "O": []}
    with open(MEMORIES_PATH, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            cat, text = line.split("\t", 1) if "\t" in line else line.split(" ", 1)
            mem[cat.strip()].append(text.strip())
    return mem


def ends_sentence(s):
    return s.endswith((".", "!", "?", ")", "♥"))


def add_addr_end(s, addr):
    # вставити звертання перед фінальним ? або !, інакше в кінець
    if s.endswith(("?", "!")):
        return s[:-1] + ", " + addr + s[-1]
    return s + ", " + addr


def good(s):
    if len(s) > MAX_LEN:
        return False
    ws = [w for w in re.split(r"[\s,.!?:)♥]+", s.lower()) if len(w) >= 5]
    return len(ws) == len(set(ws))


def make(cat, mains, follows, rng):
    s = rng.choice(mains)
    # не додавати звертання, якщо воно вже є у фразі
    r = 1.0 if re.search(r"Дарц|^Рибко|^Кицю", s) else rng.random()
    if r < P_ADDR_START:
        s = upper_first(weighted(rng, ADDR)) + ", " + lower_first(s)
    elif r < P_ADDR_START + P_ADDR_END:
        s = add_addr_end(s, weighted(rng, ADDR))
    if not ends_sentence(s):
        s += weighted(rng, END_P)
    if follows and rng.random() < P_FOLLOW and not s.endswith("♥"):
        if s.endswith(")"):
            s = s[:-1] + "."
        s += " " + rng.choice(follows)
    return s


def main():
    rng = random.Random(SEED)
    mem = load_memories()
    mains = dict(MAIN)
    mains.update(mem)

    rows, stats = [], Counter()
    for cat, target in TARGET.items():
        follows = FOLLOW_MEM if cat in mem else FOLLOW[cat]
        seen = set()
        for _ in range(target * ATTEMPTS_PER_ITEM):
            if len(seen) >= target:
                break
            s = make(cat, mains[cat], follows, rng)
            if good(s):
                seen.add(s)
        stats[cat] = len(seen)
        rows += [(cat, s) for s in sorted(seen)]

    rng.shuffle(rows)
    with open(OUT_PATH, "w", encoding="utf-8", newline="\n") as f:
        for cat, s in rows:
            f.write(f"{cat}\t{s}\n")

    chars = Counter(ch for _, s in rows for ch in s)
    lens = [len(s) for _, s in rows]
    print(f"Записано: {OUT_PATH}")
    print(f"Всього фраз: {len(rows)}")
    for cat in TARGET:
        print(f"  {cat}: {stats[cat]} (базових речень: {len(mains[cat])})")
    print(f"Довжина: мін {min(lens)}, сер {sum(lens) / len(lens):.1f}, макс {max(lens)}")
    print(f"Унікальних символів: {len(chars)}")
    print("Символи:", "".join(sorted(chars)))
    print("\nПриклади:")
    for cat, s in rng.sample(rows, 25):
        print(f"  [{cat}] {s}")


if __name__ == "__main__":
    main()
